const messages: Record<Language, Record<string, string>> = { fa, en };

type I18nValue = {
  language: Language;
  direction: "rtl" | "ltr";
  locale: string;
  setLanguage: (language: Language) => void;
  t: (key: string) => string;
  number: (value: number) => string;
  money: (value: number) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    const saved = localStorage.getItem("marketa-language");
    return saved === "en" ? "en" : "fa";
  });
  const direction = language === "fa" ? "rtl" : "ltr";
  const locale = language === "fa" ? "fa-IR" : "en-US";

  useEffect(() => {
    localStorage.setItem("marketa-language", language);
    document.documentElement.lang = language;
    document.documentElement.dir = direction;
    document.body.dir = direction;
  }, [direction, language]);

  const value = useMemo<I18nValue>(
    () => ({
      language,
      direction,
      locale,
      setLanguage,
      t: (key) => messages[language][key],
      number: (value) => value.toLocaleString(locale),
      money: (value) =>
        language === "fa"
          ? `${value.toLocaleString(locale)} تومان`
          : new Intl.NumberFormat(locale, {
              style: "currency",
              currency: "USD",
            }).format(value),
    }),
    [direction, language, locale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used inside I18nProvider");
  }
  return context;
}
"""Write the install's `.env`, once, and never again.

Run by the installer on both a first install and an update. On an update it
must find the existing file and leave it completely alone: it holds the
SECRET_KEY that signs every session token, the path to the shop's database,
and whatever timezone and day-boundary the shop was tuned to. Regenerating
any of those would at best log everyone out and at worst point the app at a
new, empty database while the real one sat untouched next to it.

It also records where the data directory is, so that every later run of
`launch.py`, `migrate.py` and `stop.py` finds the same one.

Usage:

    python configure.py --data-dir "C:\\ProgramData\\MARKETA" \
        --timezone Asia/Tehran --boundary-hour 0 --port 8000
"""

import argparse
import os
import secrets
import sys
from pathlib import Path

import marketa_runtime

_TEMPLATE = """\
# MARKETA — generated by the installer on first install.
# Edit by hand if you need to; the installer will not overwrite this file.

ENVIRONMENT=production
DEBUG=false

# The shop's database. Kept outside Program Files so that updating or even
# uninstalling the program cannot touch it.
DATABASE_URL=sqlite:///{database_path}

# Signs session tokens. Generated randomly for this install — if it
# changes, everyone is simply asked to log in again.
SECRET_KEY={secret_key}

# The shop's own clock. Reports bucket a "day" by these two values, not by
# UTC: STORE_DAY_BOUNDARY_HOUR is the hour at which one trading day hands
# over to the next, so a shop open past midnight sets it to 3 and keeps
# after-midnight sales on the day the shift began.
STORE_TIMEZONE={timezone}
STORE_DAY_BOUNDARY_HOUR={boundary_hour}

# The port MARKETA serves on, for the browser to open. Change only if
# something else on this machine already uses it.
MARKETA_PORT={port}
"""


def main() -> int:
    parser = argparse.ArgumentParser(description="Write the initial MARKETA .env.")
    parser.add_argument(
        "--data-dir",
        help="Where this install keeps its database, .env, logs and backups. "
        "Recorded for every later run.",
    )
    parser.add_argument("--timezone", default="Asia/Tehran")
    parser.add_argument("--boundary-hour", type=int, default=0)
    parser.add_argument("--port", type=int, default=marketa_runtime.DEFAULT_PORT)
    args = parser.parse_args()

    if args.data_dir:
        chosen = Path(args.data_dir)
        marketa_runtime.record_data_dir(chosen)
        # Also for this process: prepare() below reads the pointer file, but
        # the environment override is what makes the two agree even if the
        # write somehow failed silently.
        os.environ["MARKETA_DATA_DIR"] = str(chosen)

    data_directory = marketa_runtime.prepare()
    env_file = data_directory / ".env"
    if env_file.is_file():
        print(f"{env_file} already exists; keeping it.")
        return 0

    # A forward-slashed absolute path: this goes into a sqlite:/// URL, where
    # a Windows backslash would be read as an escape.
    database_path = (data_directory / "marketa.db").as_posix()
    env_file.write_text(
        _TEMPLATE.format(
            database_path=database_path,
            secret_key=secrets.token_urlsafe(48),
            timezone=args.timezone,
            boundary_hour=args.boundary_hour,
            port=args.port,
        ),
        encoding="utf-8",
    )
    print(f"Wrote {env_file}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
